import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

/**
 * prisma/schema.prisma is the single source of truth (SQLite for local development and CI).
 * This script derives the PostgreSQL schema used in production (Neon on Vercel):
 *   node prisma/make-postgres-schema.mjs            writes prisma/postgres/schema.prisma (committed)
 *   node prisma/make-postgres-schema.mjs --local    writes .local-pg/schema.prisma (git-ignored): same models, client generated into .local-pg/client,
 *                                                   used to run the test suite against a local PostgreSQL next to the SQLite client.
 * tests/m5-postgres-schema.test.ts fails when the committed file is out of date.
 */
const src = readFileSync("prisma/schema.prisma", "utf8").replace(/\r\n/g, "\n");
const datasource = /datasource db \{[\s\S]*?\n\}/;
const generator = /generator client \{[\s\S]*?\n\}/;
if (!datasource.test(src) || !generator.test(src)) throw new Error("schema.prisma: datasource or generator block not found");

export function postgresSchema({ local = false } = {}) {
  const header = `// GENERATED by prisma/make-postgres-schema.mjs from prisma/schema.prisma. Do not edit by hand.\n// PostgreSQL schema for production. DATABASE_URL is the pooled runtime connection, DIRECT_URL the direct connection used by migrations.\n\n`;
  const gen = `generator client {\n  provider = "prisma-client-js"${local ? '\n  output   = "./client"' : ""}\n}`;
  const ds = `datasource db {\n  provider  = "postgresql"\n  url       = env("DATABASE_URL")\n  directUrl = env("DIRECT_URL")\n}`;
  return header + src.replace(generator, gen).replace(datasource, ds).replace(/SQLite stores DECIMAL with NUMERIC affinity\n\/\/    \(exact up to ~15 significant digits\); PostgreSQL stores it exactly\./, "PostgreSQL stores it exactly.");
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve("prisma/make-postgres-schema.mjs")) {
  const local = process.argv.includes("--local");
  const out = local ? ".local-pg/schema.prisma" : "prisma/postgres/schema.prisma";
  mkdirSync(path.dirname(out), { recursive: true });
  writeFileSync(out, postgresSchema({ local }));
  console.log("wrote", out);
}
